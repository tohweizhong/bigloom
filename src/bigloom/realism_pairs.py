LO, HI = 110, 170
#: Test design: public and synthetic product, service, and register names. Masked as [PRODUCT-n].
PRODUCTS: tuple[str, ...] = (
    "SearchSG", "Corppass", "CorpPass", "WOGAA", "Singpass", "SingPass", "GovText", "Myinfo", "MyInfo",
    "MyCareersFuture", "PayNow", "Paynow", "SGTS", "Singapore Government Tech Stack", "GITSIR", "ScamShield", "SingCERT",
    "Enterprise Data Hub", "CDCGoWhere", "Singapore Government Design System", "SGDS",
    "Singapore Government Developer Portal", "SGDP",
    "Government Incident Reporting and Operation Centre", "Government Incident Reporting & Operation Centre", "GIROC",
    "SHIP-HATS", "MAESTRO",
    "inventory valuation service", "product hierarchy sync service", "inventory-valuation",
    "Agency Reference Data Register", "reference data register",
)
#: Test design: organisation and division names. Masked as [ORG-n].
ORGS: tuple[str, ...] = (
    r"Government Technology Agency(?: of Singapore)?(?: \(GovTech Singapore\))?(?: \(Synthetic\))?",
    "GovTech Singapore", "GovTech", "Smart Nation(?: and Digital Government Office)?", "Ministry of [A-Z][a-z]+",
    "Product & Engineering", "Government Digital Transformation", "Services, Governance & Cybersecurity",
    "Whole-of-Government", "Whole of Government",
)
#: Clues that say nothing about realism: watermarks, web-print residue, links, page numbers, template tags, icon glyphs.
CLUE = re.compile(
    r"(\(Synthetic\)|synthetic test data|All names and figures are invented\.?|This document is synthetic[^.]*\.|"
    r"https?://\S+|www\.\S+|\S+@\S+|\d{1,2}/\d{1,2}/\d{2},? \d{1,2}:\d{2} ?[AP]M(?:\s+Document)?|"
    r"(?:^|\s)\d{1,2}/\d{1,2}(?=$)|HOME / [A-Z /]+|"
    r"Synthetic corpus generated by[^.]*\.?|©\s*\d{4}[^.]*\.?|Government officials will never ask[^.]*\.|"
    r"Skip to main content|A Singapore Government Agency Website|\bPage \d+( of \d+)?\b|"
    r"\b\d+\s*\|\s*P\s*a\s*g\s*e\b|\bOFFICIAL-OPEN\b|\[\s*insert:\s*param,[^\]]*\]?|\binsert:\s*param,[^\]]*\]?|"
    r"\b(?:(?:pr|uu|bd|tx|tl)-)?\d+_prm_\d+\s*\]?|\[\s*(?=$)|(?<=^)\]\s*(?=day)|"
    r"\b(?:pr|uu|bd|tx|tl)-\s*(?=time period)|"
    r"[\ue000-\uf8ff]+|Call the 24/7 [^\n.]*Helpline at 1799[^.]*\.?|\{\{fact:[^}]+\}\}|"
    r"\bWCAG\s*:(?:\s*(?:Operable|Perceivable|Robust|Understandable|Understand)\b)?|"
    r"\b(?:BD|PR|TX|TL|UU)-\d+\s*:[^\n.]*|\bChat with us\b|"
    r"^(?:y\s+|Standards\s+Payments\s+|Payments\s+(?=Use\s+\.gov\.sg\b)|"
    r"Understand\s+(?=Education|and problems\b)|"
    r"Reliability\s+(?=Understand\b)|Trust and(?: Legitimacy\s+(?=redesigning\b)|$)"
    r"|Legitimacy\s+(?=redesigning\b)|(?:\b(?:Perceivable|Robust|Operable|Glossary)\b))|"
    r"\bControl(?=\s+(?:in digital services|user needs)\b))",
    re.IGNORECASE,
)
#: Lines from multi-column control/parameter tables, TOC dot leaders, and web-print chrome to drop before paragraph assembly.
_DROP_LINE = re.compile(
    r"(\.{4,}|^\d{1,2}[a-c]?$|"
    r"\bControl\s+Control Description\b|\bThreat ID\s*\(s\)|\bThreat\s+Threat\s+Threat Scenarios\b|"
    r"^Table [23]\s+[–-]|^(?:Dev|Dep|Use)\d\b|\b(?:Dev|Dep|Use)\d\s+to\s+(?:Dev|Dep|Use)\s*\d|"
    r"\bNIST\s+800-53\b|\bAML\.[MT]\d+\b|\b(?:ED|TD|FM|TM|RM|MS|VS|LA|RL)-C\d\b|"
    r"\bLLM\s+poisoning\b|\bPoisoning/\s*Theft\b|\bLLM\s+Theft\b|\bLLM\s+behaviour\s+manipulation\b|"
    r"\bSensitive\s+data\s+(?:leakage|disclosure)\b|\bPoison\s+Training\s+Data\b|"
    r"\btime period \((?:days|seconds)\)|\bThe time period in (?:days|seconds)\b|\bnumber of browsers \(int\)|"
    r"\bThe number of web browsers\b|\(int\)\s*conducted\.|\(days\)\s*\(int\)|"
    r"^Home\s+Products and services\b|^Interested to find out more about\b|^Why use\b|^How to use\b|^What's the latest on\b|"
    r"^Visit the\s+.*website to learn more\b|^Have questions\?\s*Email us\b|"
    r"\|\s*Government Technology Agency\b|"
    r"^Table \d+(?:\.\d+)?\s*:|^Source:\s|^Figure:\s.*\bBars:\s|"
    r"^(?:\d{1,2}\s+)?Revised\s+.*\bforecast\b)",
    re.IGNORECASE,
)


def _clean_line(raw: str) -> str:
    """Clean one extracted line and return an empty string if the line is table or web-chrome noise."""
    collapsed = re.sub(r"\s+", " ", raw).strip()
    if not collapsed or _DROP_LINE.search(collapsed):
        return ""
    if (
        re.match(r"^\d{1,2}(?:\.\d+)?\s+[A-Z]", collapsed)
        and len(collapsed.split()) <= 14
        and not collapsed.endswith((".", "!", "?"))
    ):
        return ""
    line = CLUE.sub(" ", collapsed)
    line = re.sub(r"\[\s*\]|\[\s*$|^\]\s*", " ", line)
    line = re.sub(r"\s{2,}", " ", line).strip()
    line = re.sub(r"\s+([,.;:!?])", r"\1", line)
    line = re.sub(r"\bat least\s+every\s+day\(s\)", "regularly", line, flags=re.IGNORECASE)
    line = re.sub(r"\bevery\s+day\(s\)", "periodically", line, flags=re.IGNORECASE)
    line = re.sub(r"\bat least\s+day\(s\)", "in advance", line, flags=re.IGNORECASE)
    line = re.sub(r"\bin advance\s+in advance\b", "in advance", line, flags=re.IGNORECASE)
    line = re.sub(r"\bwithin\s+(?:\]\s*)?day\(s\)", "promptly", line, flags=re.IGNORECASE)
    line = re.sub(r"\bis\s+second\(s\)\s+or less\b", "meets the target threshold", line, flags=re.IGNORECASE)
    line = re.sub(r"\bday\(s\)", "days", line, flags=re.IGNORECASE)
    line = re.sub(r"\bsecond\(s\)", "seconds", line, flags=re.IGNORECASE)
    line = re.sub(r"(?<=[.’'\".])\s+\d{1,2}$", "", line)
    return re.sub(r"\s{2,}", " ", line).strip()


def mask_names(text: str, extra_orgs: Iterable[str] = ()) -> str:
    """Replace product and organisation names with numbered tokens. One name keeps one token."""
    tokens: dict[str, str] = {}

    def sub(pattern: str, kind: str, s: str) -> str:
        def repl(m: re.Match[str]) -> str:
            key = m.group(0).lower()
            if key not in tokens:
                tokens[key] = f"[{kind}-{sum(1 for v in tokens.values() if v.startswith('[' + kind)) + 1}]"
            return tokens[key]

        return re.sub(pattern, repl, s)

    for name in sorted(PRODUCTS, key=len, reverse=True):
        text = sub(rf"\b{re.escape(name)}\b", "PRODUCT", text)
    for pattern in (*ORGS, *(re.escape(o) for o in sorted(extra_orgs, key=len, reverse=True) if o)):
        text = sub(rf"\b{pattern}", "ORG", text)
    return text


def passages(text: str) -> list[str]:
    """Split text into passages of LO to HI words, made of lines of at least six words."""
    paras: list[str] = []
    cur: list[str] = []
    in_multi_col_table = False
    for raw in text.splitlines():
        collapsed = re.sub(r"\s+", " ", raw).strip()
        if re.match(r"^Table [23]\s+[–-]", collapsed):
            in_multi_col_table = True
            continue
        if in_multi_col_table:
            if re.match(r"^5\s+Recommended controls\b", collapsed):
                in_multi_col_table = False
            elif re.match(r"^\d{1,2}\s+[A-Z]{2,}[^:]*:", collapsed):
                pass
            else:
                continue
        line = _clean_line(raw)
        if not line:
            if not collapsed and cur:
                paras.append(" ".join(cur))
                cur = []
            continue
        if len(line.split()) >= 6:
            cur.append(line)
        elif cur and line and not cur[-1].endswith((".", "!", "?")):
            # A short tail of a wrapped sentence ends the paragraph. Keep it.
            cur.append(line)
            paras.append(" ".join(cur))
            cur = []
        elif cur:
            paras.append(" ".join(cur))
            cur = []
    if cur:
        paras.append(" ".join(cur))
    cleaned_paras: list[str] = []
    for p in paras:
        p = re.sub(r"\bat least\s+days(?:\s+in advance)?\b", "in advance", p, flags=re.IGNORECASE)
        p = re.sub(r"\bin advance\s+in advance\b", "in advance", p, flags=re.IGNORECASE)
        p = re.sub(r"\bwithin\s+days\b", "promptly", p, flags=re.IGNORECASE)
        p = re.sub(r"\bwithin\s*\.", "promptly.", p, flags=re.IGNORECASE)
        p = re.sub(r"\bis\s+seconds\s+or less\b", "meets the target threshold", p, flags=re.IGNORECASE)
        cleaned_paras.append(re.sub(r"\s{2,}", " ", p).strip())
    out: list[str] = []
    buf: list[str] = []
    for p in cleaned_paras:
        buf.extend(p.split())
        if len(buf) >= LO:
            out.append(" ".join(buf[:HI]))
            buf = []
    if len(buf) >= 75:
        out.append(" ".join(buf[:HI]))
    return out


def _pool(files: Sequence[Path]) -> list[tuple[str, int, str]]:
    return [
        (f.name, i, p)
        for f in files
        if "DPO Registration Instruction Guide" not in f.name
        and "spp model development procedure manual" not in f.name.lower()
        for i, p in enumerate(passages(text_of(f)))
    ]


def _spread(items: list[tuple[str, int, str]], n: int) -> list[tuple[str, int, str]]:
    by: dict[str, list[tuple[str, int, str]]] = {}
    for it in items:
        by.setdefault(it[0], []).append(it)
    out: list[tuple[str, int, str]] = []
    while len(out) < n and any(by.values()):
        for k in sorted(by):
            if by[k] and len(out) < n:
                out.append(by[k].pop())
    return out


def build_pairs(real_dir: Path, synth_dir: Path, out_dir: Path, n: int, seed: int,
                extra_orgs: Iterable[str] = ()) -> dict[str, Any]:
    """Write `out_dir/pairs.md` with masked blind pairs. Return the answer key (never written here)."""
    real = _pool(sorted(p for p in real_dir.iterdir() if p.is_file()))
    synth_files = [f for f in sorted(synth_dir.iterdir()) if f.is_file()]
    synth = _pool(synth_files)
    rng = random.Random(seed)
    rng.shuffle(real)
    rng.shuffle(synth)
    real_s, synth_s = _spread(real, n), _spread(synth, n)
    count = min(len(real_s), len(synth_s))
    orgs = list(extra_orgs)
    lines, key = ["# Passage pairs", ""], {}
    for i in range(count):
        real_first = rng.random() < 0.5
        a, b = (real_s[i], synth_s[i]) if real_first else (synth_s[i], real_s[i])
        pid = f"P{i + 1:02d}"
        key[pid] = {"real": "A" if real_first else "B", "real_src": real_s[i][0], "synth_src": synth_s[i][0]}
        lines += [f"## {pid}", "", "### A", "", mask_names(a[2], orgs), "", "### B", "", mask_names(b[2], orgs), ""]
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "pairs.md").write_text("\n".join(lines), encoding="utf-8")
    return {"pairs": count, "real_pool": len(real), "synth_pool": len(synth), "key": key}


def score(key: dict[str, Any], verdicts: Sequence[dict[str, Any]]) -> int:
    """Return the number of verdicts that name the real passage correctly."""
    return sum(1 for v in verdicts if key.get(v.get("pair"), {}).get("real") == v.get("real"))


def samples(synth_dir: Path, n: int = 2, words: int = 150) -> list[dict[str, str]]:
    """Return `n` passages of about `words` words from different synthetic files, for the user to read."""
    out: list[dict[str, str]] = []
    for f in sorted(p for p in synth_dir.iterdir() if p.is_file() and "-2mb_final" in p.name):
        found = [p for p in passages(text_of(f)) if len(p.split()) >= 100]
        if found:
            out.append({"file": f.name, "text": " ".join(found[len(found) // 2].split()[:words])})
        if len(out) >= n:
            break
    return out


